"""Isolated sandbox for VS Code debug sessions (used by .vscode/tasks.json).

Debugging train/retrain would otherwise overwrite committed state (artifacts/champion, mlflow.db,
reports/). This script writes .debug/config.yaml: a copy of configs/config.yaml with every output path
redirected into .debug/. It is regenerated on every launch, so it always matches the real config.
The launch configs point FRAUD_CONFIG at it.

On first use it also seeds the sandbox with the current champion bundle, its archive and the
replay stream, so the API and retrain can be debugged without training first.

    python scripts/debug_sandbox.py                     # prepare sandbox
    python scripts/debug_sandbox.py --wait-api URL      # prepare, then block until URL/health answers

Reset the sandbox by deleting the .debug folder.
"""
from __future__ import annotations

import argparse
import shutil
import sys
import time
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SANDBOX = ROOT / ".debug"


def prepare() -> Path:
    cfg = yaml.safe_load((ROOT / "configs" / "config.yaml").read_text(encoding="utf-8"))
    # Paths are resolved against the project root, so ".debug/..." lands in the sandbox.
    cfg["artifacts"].update(champion_dir=".debug/artifacts/champion", archive_dir=".debug/artifacts/archive",
                            reports_dir=".debug/reports")
    cfg["mlflow"].update(tracking_uri="sqlite:///.debug/mlflow.db", artifact_dir=".debug/mlartifacts")
    cfg["serving"]["store_path"] = ".debug/store/predictions.db"
    cfg["data"]["stream_path"] = ".debug/stream/stream.parquet"

    SANDBOX.mkdir(exist_ok=True)
    out = SANDBOX / "config.yaml"
    header = "# GENERATED by scripts/debug_sandbox.py from configs/config.yaml - edit that file instead.\n"
    out.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")

    seeds = [(ROOT / "artifacts" / "champion", SANDBOX / "artifacts" / "champion"),
             (ROOT / "artifacts" / "archive", SANDBOX / "artifacts" / "archive"),
             (ROOT / "data" / "stream" / "stream.parquet", SANDBOX / "stream" / "stream.parquet")]
    for src, dst in seeds:
        if src.exists() and not dst.exists():
            dst.parent.mkdir(parents=True, exist_ok=True)
            (shutil.copytree if src.is_dir() else shutil.copy2)(src, dst)
            print(f"seeded {dst.relative_to(ROOT)}")
    print(f"sandbox ready: {out.relative_to(ROOT)}")
    return out


def wait_for_api(url: str, timeout: float = 120) -> None:
    deadline = time.time() + timeout
    health = f"{url.rstrip('/')}/health"
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(health, timeout=2) as r:
                if r.status == 200:
                    print(f"API up: {health}")
                    return
        except OSError:
            pass
        time.sleep(1)
    sys.exit(f"API at {health} did not answer within {timeout:.0f}s - start 'API: uvicorn (sandbox)' first")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--wait-api", metavar="URL")
    args = ap.parse_args()
    prepare()
    if args.wait_api:
        wait_for_api(args.wait_api)
